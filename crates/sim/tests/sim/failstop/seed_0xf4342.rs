/// The history runs to the end with no violation, the judge of every tick included.
#[test]
fn a_forged_staged_file_after_a_day_long_step_does_not_trip_seed_0xf4342() {
    let opts = Opts {
        drawn: true,
        block_crash_law: true,
        lying_wal_sync: false,
        after_restart: AfterRestart::Busy,
        clock_law: ClockLaw::PerTick,
        staging_fs: true,
        ..Opts::default()
    };
    let ops = ops();
    assert_eq!(ops.len(), 188);
    if let Err(failure) = run_ops(Seed::new(0xf4342), &ops, &opts) {
        panic!("step {}: {}", failure.step, failure.violation);
    }
}
